using System.Diagnostics.CodeAnalysis;
using Npgsql;
using Testcontainers.PostgreSql;

namespace Quorum.Integration.Tests.Fixtures;

/// <summary>
/// One PostgreSQL container for the whole test assembly; every app instance gets its own database.
/// </summary>
public sealed class PostgresFixture : IAsyncLifetime
{
    private const string TemplateName = "quorum_template";

    // Every app instance keeps its own connection pool, and the apps of a whole run live side by side: the default 100 connections run out.
    private readonly PostgreSqlContainer _container = new PostgreSqlBuilder("postgres:17-alpine")
        .WithCommand("-c", "max_connections=500")
        .Build();

    public async ValueTask InitializeAsync()
    {
        await _container.StartAsync();
        await CreateTemplateAsync();
    }

    public async ValueTask DisposeAsync() => await _container.DisposeAsync();

    /// <summary>A new database with every module's schema already applied, cloned from the template.</summary>
    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "The database name is generated by the test, never user input.")]
    public async Task<string> CreateDatabaseAsync()
    {
        var name = $"quorum_{Guid.NewGuid():N}";

        await using var connection = new NpgsqlConnection(_container.GetConnectionString());
        await connection.OpenAsync();
        await using var command = new NpgsqlCommand($"CREATE DATABASE \"{name}\" TEMPLATE \"{TemplateName}\"", connection);
        await command.ExecuteNonQueryAsync();

        return ConnectionStringFor(name);
    }

    // Applying every module's migrations is the bulk of an app's start, and nearly every test starts one: do it once
    // by starting an app on the template (the same code path as production), and let each test database copy the result.
    [SuppressMessage("Security", "CA2100:Review SQL queries for security vulnerabilities", Justification = "The database name is a constant of the fixture.")]
    private async Task CreateTemplateAsync()
    {
        await using (var connection = new NpgsqlConnection(_container.GetConnectionString()))
        {
            await connection.OpenAsync();
            await using var create = new NpgsqlCommand($"CREATE DATABASE \"{TemplateName}\"", connection);
            await create.ExecuteNonQueryAsync();
        }

        var templateConnectionString = ConnectionStringFor(TemplateName);
        // Start migrates before it returns; the app is not used.
        await QuorumApp.Start(templateConnectionString).DisposeAsync();

        // CREATE DATABASE ... TEMPLATE needs the template to have no other sessions.
        NpgsqlConnection.ClearAllPools();
        await using var cleanup = new NpgsqlConnection(_container.GetConnectionString());
        await cleanup.OpenAsync();
        await using var terminate = new NpgsqlCommand(
            "SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = @name AND pid <> pg_backend_pid()", cleanup);
        terminate.Parameters.AddWithValue("name", TemplateName);
        await terminate.ExecuteNonQueryAsync();
    }

    private string ConnectionStringFor(string database) =>
        new NpgsqlConnectionStringBuilder(_container.GetConnectionString()) { Database = database }.ConnectionString;
}
