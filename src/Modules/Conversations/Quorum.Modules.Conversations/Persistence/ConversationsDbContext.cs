using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;
using Quorum.Modules.Conversations.Domain;
using Quorum.Shared.Persistence;
using Quorum.Shared.Tenancy;

namespace Quorum.Modules.Conversations.Persistence;

internal sealed class ConversationsDbContext(
    DbContextOptions<ConversationsDbContext> options,
    ITenantContext tenantContext,
    ICurrentUser currentUser) : DbContext(options)
{
    public const string Schema = "conversations";

    public DbSet<Conversation> Conversations => Set<Conversation>();

    public DbSet<Message> Messages => Set<Message>();

    public DbSet<Attachment> Attachments => Set<Attachment>();

    private Guid? CurrentTenantId => tenantContext.TenantId;

    private Guid? CurrentUserId => currentUser.UserId;

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasDefaultSchema(Schema);

        modelBuilder.Entity<Conversation>(conversation =>
        {
            conversation.ToTable("conversations");

            // Ids are generated by the domain (UUIDv7); a new message reached through the navigation must be an insert.
            conversation.Property(c => c.Id).ValueGeneratedNever();
            conversation.Property(c => c.Title).HasMaxLength(Conversation.MaxTitleLength);
            conversation.HasIndex(c => new { c.TenantId, c.UserId, c.UpdatedAt });
            conversation.HasMany(c => c.Messages).WithOne().HasForeignKey(m => m.ConversationId).OnDelete(DeleteBehavior.Cascade);
            conversation.Navigation(c => c.Messages).UsePropertyAccessMode(PropertyAccessMode.Field);

            // Conversations are private: only their owner, in their tenant, ever sees them.
            conversation.HasQueryFilter(c => c.TenantId == CurrentTenantId && c.UserId == CurrentUserId);
        });

        modelBuilder.Entity<Message>(message =>
        {
            message.ToTable("messages");
            message.Property(m => m.Id).ValueGeneratedNever();
            message.Property(m => m.Role).HasConversion<string>().HasMaxLength(20);
            message.Property(m => m.Status).HasConversion<string>().HasMaxLength(20);
            message.HasIndex(m => new { m.ConversationId, m.CreatedAt });
            message.HasQueryFilter(m => m.TenantId == CurrentTenantId);
        });

        modelBuilder.Entity<Attachment>(attachment =>
        {
            attachment.ToTable("attachments");
            attachment.Property(a => a.Id).ValueGeneratedNever();
            attachment.Property(a => a.FileName).HasMaxLength(Attachment.MaxFileNameLength);
            attachment.Property(a => a.MediaType).HasMaxLength(100);
            attachment.Property(a => a.ContentHash).HasMaxLength(64);
            attachment.HasOne<Conversation>().WithMany().HasForeignKey(a => a.ConversationId).OnDelete(DeleteBehavior.Cascade);

            // The same content cannot be attached twice to a conversation, even by two concurrent uploads.
            attachment.HasIndex(a => new { a.ConversationId, a.ContentHash }).IsUnique();
            attachment.HasQueryFilter(a => a.TenantId == CurrentTenantId);
        });
    }
}

internal sealed class ConversationsDbContextDesignFactory : IDesignTimeDbContextFactory<ConversationsDbContext>
{
    public ConversationsDbContext CreateDbContext(string[] args) =>
        new(ModuleDbContextExtensions.DesignTimeOptions<ConversationsDbContext>(ConversationsDbContext.Schema), NoTenantContext.Instance, NoCurrentUser.Instance);

    private sealed class NoCurrentUser : ICurrentUser
    {
        public static NoCurrentUser Instance { get; } = new();

        public Guid? UserId => null;
    }
}
